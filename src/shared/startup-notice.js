/**
 * src/shared/startup-notice.js —— 启动时怎么让用户「看得见它在哪」（**纯函数**）
 * =====================================================================
 * 为什么需要它：卡片是**置底**的（ADR-012，这是产品定位）。代价是一个很具体的
 * 首次体验问题 —— 用户装完、双击、然后**屏幕上什么都没有**（桌面上只要开着窗口，
 * 卡片就被盖住了，而托盘并不响）。第一反应必然是「装了没反应 / 是不是失败了」。
 * 本项目最警戒的就是这类「看起来像 bug」的形态。
 *
 * ⇒ 启动时给一次**短暂**的可见提示，然后回到置底。两条铁律卡在中间：
 *    · **L2（不打扰）**：只有**第一次**才弹系统气泡，之后永远不弹；
 *    · **可见性**：第一次多停一会儿（够读完一句话），之后只闪一下（够看到它在哪）。
 *
 * ⚠️ 这里只做**决策**。真正的置顶与回落由主进程执行（它要碰 Electron），
 *    这样「第一次和以后分别该怎样」这件事可以被离线断言穷举 ——
 *    而它恰恰是最容易在小改动里被悄悄改坏的东西。
 * =====================================================================
 */

export function startupNotice(opts = {}) {
  const firstRun = !!opts.firstRun;
  if (firstRun) {
    return {
      frontMs: 6000,
      balloon: true,
      balloonTitle: '晨报机已经就位',
      balloonText: '卡片贴在桌面右下角、在所有窗口下面，所以平时会被窗口盖住。点托盘图标可以展开／收起。',
    };
  }
  return { frontMs: 1500, balloon: false, balloonTitle: '', balloonText: '' };
}