/**
 * src/main/diag-flags.js —— 诊断开关（零依赖 · 纯函数）
 * =====================================================================
 * 一句话：**把"为了取证而临时改变窗口行为"的开关，收进一个可开关、可回归、
 * 而且能被离线证明的地方。**
 *
 * ---------------------------------------------------------------------
 * 它为什么存在（2026-09-20）
 * ---------------------------------------------------------------------
 * 用户实测反馈：卡片上的拖动把手 `.grip` **拖不动**。
 * 我们查到两个事实：
 *   · 本机已验证：`window.js` 里卡片窗口是 `resizable: false`，且 `card.js`
 *     里**没有任何 JS 拖动代码** —— 拖动**唯一**依赖 CSS
 *     `-webkit-app-region: drag`（`card.css` 的 `.grip`）；
 *   · 外部证据：有可直接对照的 A/B（同配置下把 `resizable` 改回 `true`，
 *     无边框窗口立刻恢复可拖）。另有一条官方已知坑：
 *     `-webkit-app-region: drag` 在 DevTools 打开时会失灵。
 *
 * 于是"是不是 `resizable: false` 干的"这个判断，目前只是**高置信推论**，不是
 * 本机已验证的事实。本项目对这两者的区别很敏感（见 `R-A04`）：
 * 写进留痕的推论，必须标明它是推论。
 *
 * 取证的办法就是让它跑一次真的 —— 于是需要这个开关。
 *
 * ---------------------------------------------------------------------
 * 为什么单独成一个模块（对应项目硬规则 R-B11）
 * ---------------------------------------------------------------------
 * 解析一个环境变量**不需要 Electron**。写在 `window.js` 里的话，想验证它就得先
 * 启动整个 Electron —— 而本机沙箱里 Electron 起不来（GPU 进程崩溃），
 * 于是这段逻辑**永远没法被验证**：见 `tools/test-diag-flags.mjs`。
 *
 * ---------------------------------------------------------------------
 * ⚠️ 取证的代价，以及为什么它必须"默认为关"
 * ---------------------------------------------------------------------
 * `resizable: true` **不是**修复方案，只是诊断手段。长期打开它有真实代价：
 * 用户可以拖窗口边缘改尺寸，而**验收 6 要的是精确的固定尺寸**（360×44 / 360×520）。
 * 所以本模块的默认值**必须是 false**，开关只应在一个终端会话里临时打开。
 *
 * 另有一条纪律：`M0_DIAG_RESIZABLE` 是**临时**开关。拖动改为 JS 手动实现之后
 * （这也是 ADR-011 壁纸层形态的必然要求），本模块与这个开关都应一并退役。
 *
 * ---------------------------------------------------------------------
 * 解析口径（刻意偏"宁可认出来，也不要静默失效"）
 * ---------------------------------------------------------------------
 * 这里最危险的错误是**假阴性**：开关明明设了却解析成 false → 诊断跑成默认态 →
 * 得出「`resizable` 跟拖动无关」这个**错误结论**，然后被写进留痕。
 * 假阳性（没设却当成 true）的后果轻得多：多跑一次诊断态而已。
 *
 * 所以口径取宽：字符串走白名单（大小写与首尾空格不敏感），
 * 布尔直接采信，数字只认 1。其余一律 false。
 *
 *   设了   → '1' 'true' 'TRUE' ' on ' 'yes' true(布尔) 1(数字)
 *   没设   → undefined null '' '  ' '0' 'false' 'off' 'no' '2' {} []
 * =====================================================================
 */

/** 传递"临时打开 resizable"的环境变量名（写：终端；读：主进程） */
export const DIAG_RESIZABLE_ENV = 'M0_DIAG_RESIZABLE';

/** 视为"真"的字符串（比较前会 trim + toLowerCase） */
const TRUTHY = Object.freeze(['1', 'true', 'on', 'yes']);

/**
 * 把环境变量里的原始值解析成布尔。
 * @param {unknown} raw
 * @returns {boolean}
 */
export function parseFlag(raw) {
  // 布尔直接采信 —— 将来若从配置文件而非环境变量读取，不必改调用方
  if (raw === true) return true;
  if (raw === false) return false;
  // 数字只认 1。刻意不写 `Boolean(raw)`：那样 0 与 NaN 的口径会变得可疑
  if (typeof raw === 'number') return raw === 1;
  if (typeof raw !== 'string') return false;
  return TRUTHY.includes(raw.trim().toLowerCase());
}

/**
 * 本次运行是否处于"拖动诊断态"（临时把卡片窗口设为可缩放）。
 *
 * ⚠️ `env` 允许为 null/undefined —— 不许抛错。启动路径上抛错等于应用起不来，
 *    代价远大于"开关没生效"。
 *
 * @param {Record<string, unknown>} [env]
 * @returns {boolean}
 */
export function diagResizable(env = process.env) {
  return parseFlag(env ? env[DIAG_RESIZABLE_ENV] : undefined);
}
